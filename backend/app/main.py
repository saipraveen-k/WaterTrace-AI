from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from app.api.v1.router import api_router
from app.core.config import settings

app = FastAPI(
    title="WaterTrace AI",
    description="Water infrastructure incident intelligence platform",
    version="1.0.0",
    docs_url="/docs",
    redoc_url="/redoc",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.allowed_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(api_router)


@app.get("/health")
async def health_check():
    return {"status": "healthy", "service": "watertrace-ai-backend"}


@app.get("/")
async def root():
    return {
        "service": "WaterTrace AI Backend",
        "version": "1.0.0",
        "docs": "/docs",
    }
